export type CoachBotStrings = (typeof S)[CoachBotLocale];
export const coachStrings = (locale: CoachBotLocale): CoachBotStrings => S[locale];

/** "Fri 12 Sep 15:00" in the coach's zone and the reader's language. */
export function whenLabel(at: Date, tz: string, locale: string): string {
  const day = new Intl.DateTimeFormat(locale, { weekday: "short", day: "numeric", month: "short", timeZone: tz }).format(at);
  const time = new Intl.DateTimeFormat(locale, { hour: "2-digit", minute: "2-digit", hour12: false, timeZone: tz }).format(at);
  return `${day} ${time}`;
}

export function dayOnlyLabel(dateStr: string, locale: string): string {
  return new Intl.DateTimeFormat(locale, { weekday: "short", day: "numeric", month: "short", timeZone: "UTC" }).format(new Date(`${dateStr}T00:00:00Z`));
}
